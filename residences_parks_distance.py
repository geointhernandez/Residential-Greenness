#Calcular cuántos parques tiene una persona en una radio de 1 kilómetro

import geopandas as gpd
import pandas as pd

# 1. Cargar tus archivos CSV muestra

df_personas = df_sm_merida
df_parques = df_parques_merida

# 2. Convertir el DataFrame de personas a GeoDataFrame (EPSG:4326)
gdf_personas = gpd.GeoDataFrame(
    df_personas,
    geometry=gpd.points_from_xy(df_personas.longitud, df_personas.latitud),
    crs="EPSG:4326",
)

# 3. Convertir el DataFrame de parques a GeoDataFrame (EPSG:4326)
gdf_parques = gpd.GeoDataFrame(
    df_parques,
    geometry=gpd.points_from_xy(df_parques.longitud, df_parques.latitud),
    crs="EPSG:4326",
)

# 4. Reproyectar ambos al CRS métrico oficial para la zona de Mérida (UTM 16N -> EPSG:32616)
# Este paso garantiza que el radio de "1000" represente exactamente metros en el terreno
gdf_personas = gdf_personas.to_crs(epsg=32616)
gdf_parques = gdf_parques.to_crs(epsg=32616)

# 5. Crear el radio (Buffer) de 1 kilómetro (1000 metros) alrededor de cada persona
# Creamos una copia para mantener la geometría de punto original intacta en el dataframe final
gdf_buffers = gdf_personas.copy()
gdf_buffers["geometry"] = gdf_buffers.geometry.buffer(1000)

# 6. Realizar una unión espacial (Spatial Join)
# 'predicate="contains"' o "within" intersecta los parques que se encuentran DENTRO del área del buffer
sjoin_resultado = gpd.sjoin(
    gdf_parques, gdf_buffers, how="inner", predicate="within"
)

# 7. Agrupar el resultado por el ID de la persona para contar cuántos parques le corresponden
# Agregamos .reset_index() para que 'id_encuestado' sea una columna y se pueda hacer el merge por clave
conteos = sjoin_resultado.groupby("id_encuestado").size().to_frame("parques_en_1km").reset_index()

# 8. Unir el conteo de vuelta al DataFrame original de personas
# Usamos 'left_join' para asegurar que si una persona tiene 0 parques a la redonda, se mantenga en la lista
df_final = df_personas.merge(conteos, on="id_encuestado", how="left")

# 9. Llenar los valores NaN con 0 (para las personas que no tengan ningún parque a menos de 1km)
df_final["parques_en_1km"] = df_final["parques_en_1km"].fillna(0).astype(int)

# === DESPLEGAR RESULTADO ===
print("Resultado final con el conteo de parques en un radio de 1 km:")
print(df_final[["id_encuestado", "latitud", "longitud", "parques_en_1km"]])

#Eliminar los registros duplicados en la fila id_encuestado
df_final = df_final.drop_duplicates(subset=['id_encuestado'])
df_final.shape

df_final.head()

df_final[df_final['parques_en_1km'] > 0]

